#!/usr/bin/env node
// Keeps README.md and CLAUDE.md in step with the repo — the deterministic half.
//
// Same split as the translation pipeline (scripts/translation-status.mjs):
// this script decides, a model only writes. It does two jobs.
//
// 1. Generated blocks. The parts of the docs that are pure fact — the project
//    tree, the scripts tables, the islands table — sit between
//    `<!-- docs:<name>:start -->` / `<!-- docs:<name>:end -->` markers and are
//    rebuilt from the code. Only their *structure* is generated: the prose in
//    them (a tree entry's `# note`, a script's description, an island's "why")
//    is read back out of the current doc and kept, keyed by path / script /
//    island. A new entry comes out with empty prose and is listed as `unnoted`.
//
// 2. Drift. Prose outside the blocks cannot be generated, so instead this
//    records a fingerprint of the repo's shape — tracked files, scripts,
//    dependency names, islands, external hosts — in docs/docs-sync.snapshot.json.
//    When the live fingerprint differs from it, the docs were last reviewed
//    against a different repo, and the differences are listed as `changes`.
//    /sync-docs (Claude) reviews the prose against them, then runs --accept.
//
//   node scripts/docs-sync.mjs            report; exit 1 only if a block is stale
//   node scripts/docs-sync.mjs --json     { stale, changes, unnoted, problems }
//   node scripts/docs-sync.mjs --write    rebuild the generated blocks
//   node scripts/docs-sync.mjs --accept   record the current shape as reviewed
//
// Like an untranslated post, unreviewed drift is a valid state (exit 0): the
// sync-docs workflow picks it up after the push. A stale block is not — it is
// a mechanical fix (`pnpm docs:write`), so the pre-push hook fails on it.
//
// Limit: the fingerprint sees the repo's shape, not behaviour. Changing what a
// component does without adding, removing or renaming anything is invisible
// here; re-run /sync-docs by hand when a change like that alters a documented
// rule.
import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

export const SNAPSHOT = 'docs/docs-sync.snapshot.json'
export const DOCS = ['README.md', 'CLAUDE.md']

/** Files whose churn says nothing about the repo's shape. */
const IGNORED = [
  /^src\/data\/article-content\//, // article bodies: content, not structure
  /^public\/assets\//, // images and audio
  /^docs\/sbom\//, // generated by pnpm sbom:write
  /^pnpm-lock\.yaml$/,
  /^README\.md$/,
  /^CLAUDE\.md$/,
  /^docs\/docs-sync\.snapshot\.json$/,
]

/** Scripts too internal to list (prepare only installs the git hooks). */
const UNLISTED_SCRIPTS = new Set(['prepare'])

/** Files scanned for external origins — the hosts the CSP and SBOM must track. */
const HOST_SOURCES = ['src/layouts/Base.astro', 'src/styles/global.css', 'public/_headers']

/**
 * What the README's project tree shows. Each root is listed from the tracked
 * files under it; a `collapse`d directory is one line (its contents are not
 * structure worth listing), `exclude` drops files, and a directory with a
 * single child is folded into one line (`api/comments.ts`).
 */
export const TREE_ROOTS = [
  { root: 'public', collapse: ['public/assets/images', 'public/assets/audio'] },
  {
    root: 'src',
    exclude: [/\.test\.ts$/, /\.d\.ts$/],
    collapse: ['src/pages/[lang]', 'src/data/article-content', 'src/styles/astryx'],
  },
  {
    root: 'docs',
    exclude: [/^docs\/docs-sync\.snapshot\.json$/],
    collapse: ['docs/adr', 'docs/trd', 'docs/sbom'],
  },
  { root: 'eslint-rules', collapse: ['eslint-rules'] },
  { root: 'scripts', collapse: ['scripts'] },
  { root: 'supabase/migrations', collapse: ['supabase/migrations'] },
]

// ---------------------------------------------------------------- blocks ----

const markers = (name) => [`<!-- docs:${name}:start -->`, `<!-- docs:${name}:end -->`]

/** The first line of every block, for a human who opens the file. */
export const BLOCK_NOTE =
  '<!-- Generated by `pnpm docs:write` from the code; only the prose cells are kept. Edit those, not the rows. -->'

/** The text between a block's markers, or null when the doc has no such block. */
export function readBlock(doc, name) {
  const [start, end] = markers(name)
  const i = doc.indexOf(start)
  const j = doc.indexOf(end)
  if (i === -1 || j === -1 || j < i) return null
  return doc.slice(i + start.length, j)
}

/** The doc with a block's contents replaced; markers stay where they are. */
export function replaceBlock(doc, name, body) {
  const [start, end] = markers(name)
  const i = doc.indexOf(start)
  const j = doc.indexOf(end)
  if (i === -1 || j === -1 || j < i) throw new Error(`no ${name} block`)
  return `${doc.slice(0, i + start.length)}\n${BLOCK_NOTE}\n${body.trim()}\n${doc.slice(j)}`
}

/** Split a markdown table row on unescaped pipes; null for anything else. */
function tableCells(line) {
  const t = line.trim()
  if (!t.startsWith('|') || !t.endsWith('|')) return null
  return t
    .slice(1, -1)
    .split(/(?<!\\)\|/)
    .map((c) => c.trim())
}

const isRule = (cells) => cells.every((c) => /^:?-+:?$/.test(c))

// ------------------------------------------------------------------ tree ----

/** Path → note, read back out of a rendered tree (keys have no trailing slash). */
export function parseTreeNotes(block) {
  const notes = new Map()
  const stack = []
  for (const line of (block ?? '').split('\n')) {
    const m = /^((?:│ {3}| {4})*)(├── |└── )?(\S+)(?:\s+# (.*))?$/.exec(line)
    if (!m || line.startsWith('```')) continue
    const depth = m[2] ? m[1].length / 4 + 1 : 0
    const name = m[3].replace(/…$/, '')
    const path = (depth === 0 ? '' : (stack[depth - 1] ?? '')) + name
    stack[depth] = path.endsWith('/') ? path : `${path}/`
    stack.length = depth + 1
    if (m[4]) notes.set(path.replace(/\/$/, ''), m[4].trim())
  }
  return notes
}

/** Nested { dirs, files } for the paths under one root. */
function buildTree(paths, { root, exclude = [], collapse = [] }) {
  const node = () => ({ dirs: new Map(), files: [] })
  const top = node()
  for (const p of paths) {
    if (p !== root && !p.startsWith(`${root}/`)) continue
    if (exclude.some((re) => re.test(p))) continue
    // Stop at a collapsed directory: it is a leaf, whatever is inside it.
    const hit = collapse.find((c) => p === c || p.startsWith(`${c}/`))
    const rel = (hit ?? p).slice(root.length + 1)
    if (rel === '') continue
    const parts = rel.split('/')
    let cur = top
    for (const [i, part] of parts.entries()) {
      const last = i === parts.length - 1
      if (last && !hit) {
        if (!cur.files.includes(part)) cur.files.push(part)
      } else {
        if (!cur.dirs.has(part)) cur.dirs.set(part, node())
        cur = cur.dirs.get(part)
        if (last) cur.collapsed = true
      }
    }
  }
  return top
}

const byName = (a, b) => (a < b ? -1 : a > b ? 1 : 0)

/** Lines of [indentPrefix, name, path] for one tree, folding single-child dirs. */
function treeLines(tree, path, prefix, out) {
  const entries = [
    ...[...tree.dirs.entries()].sort(([a], [b]) => byName(a, b)).map(([n, d]) => ({ n, d })),
    ...[...tree.files].sort(byName).map((n) => ({ n })),
  ]
  entries.forEach((e, i) => {
    const last = i === entries.length - 1
    let name = e.n
    let full = `${path}/${e.n}`
    let d = e.d
    // Fold a chain of single-child directories into one line.
    while (d && !d.collapsed && d.dirs.size + d.files.length === 1) {
      if (d.files.length === 1) {
        name += `/${d.files[0]}`
        full += `/${d.files[0]}`
        d = null
      } else {
        const [n, next] = [...d.dirs.entries()][0]
        name += `/${n}`
        full += `/${n}`
        d = next
      }
    }
    if (d) name += '/'
    // A leaf is a file or a collapsed directory; only leaves need a note.
    out.push([`${prefix}${last ? '└── ' : '├── '}`, name, full, !d || d.collapsed])
    if (d && !d.collapsed) treeLines(d, full, `${prefix}${last ? '    ' : '│   '}`, out)
  })
}

/** The README project tree, as a fenced block, keeping notes by path. */
export function renderTree(paths, notes, roots = TREE_ROOTS) {
  const rows = []
  for (const spec of roots) {
    rows.push(['', `${spec.root}/`, spec.root, !!spec.collapse?.includes(spec.root)])
    const top = buildTree(paths, spec)
    if (!spec.collapse?.includes(spec.root)) treeLines(top, spec.root, '', rows)
  }
  const width = Math.max(...rows.map(([p, n]) => p.length + n.length)) + 2
  const lines = rows.map(([p, n, full]) => {
    const note = notes.get(full)
    return note ? `${p}${n}`.padEnd(width) + `# ${note}` : `${p}${n}`
  })
  const unnoted = rows.filter(([, , full, leaf]) => leaf && !notes.get(full)).map(([, , f]) => f)
  return { body: ['```', ...lines, '```'].join('\n'), unnoted }
}

// --------------------------------------------------------------- scripts ----

/** name → { usage, description } from a `| `pnpm x` | … |` table. */
export function parseScriptRows(block) {
  const rows = new Map()
  for (const line of (block ?? '').split('\n')) {
    const cells = tableCells(line)
    if (!cells || cells.length < 2 || isRule(cells)) continue
    const m = /^`pnpm (\S+?)( [^`]*)?`$/.exec(cells[0])
    if (m) rows.set(m[1], { usage: (m[2] ?? '').trim(), description: cells[1] })
  }
  return rows
}

/** The README scripts table, one row per listed package.json script. */
export function renderScriptsTable(scriptNames, rows) {
  const names = scriptNames.filter((n) => !UNLISTED_SCRIPTS.has(n))
  const out = ['| Command | Description |', '| --- | --- |']
  for (const n of names) {
    const r = rows.get(n) ?? { usage: '', description: '' }
    out.push(`| \`pnpm ${n}${r.usage ? ` ${r.usage}` : ''}\` | ${r.description} |`)
  }
  return {
    body: out.join('\n'),
    unnoted: names.filter((n) => !rows.get(n)?.description),
  }
}

/** name → { usage, description } from a ```bash block of `pnpm x  # …` lines. */
export function parseCommandLines(block) {
  const rows = new Map()
  for (const line of (block ?? '').split('\n')) {
    const m = /^pnpm (\S+)(.*?)(?:\s+# (.*))?$/.exec(line.trim())
    if (m) rows.set(m[1], { usage: m[2].trim(), description: (m[3] ?? '').trim() })
  }
  return rows
}

/** The CLAUDE.md command list: a ```bash block with aligned comments. */
export function renderCommandLines(scriptNames, rows) {
  const names = scriptNames.filter((n) => !UNLISTED_SCRIPTS.has(n))
  const cmds = names.map((n) => {
    const r = rows.get(n)
    return [`pnpm ${n}${r?.usage ? ` ${r.usage}` : ''}`, r?.description ?? '']
  })
  const width = Math.max(...cmds.map(([c]) => c.length)) + 2
  const lines = cmds.map(([c, d]) => (d ? `${c.padEnd(width)}# ${d}` : c))
  return {
    body: ['```bash', ...lines, '```'].join('\n'),
    unnoted: names.filter((n) => !rows.get(n)?.description),
  }
}

// --------------------------------------------------------------- islands ----

/** The allowlist on local/no-unlisted-island in eslint.config.js. */
export function islandAllowlist(eslintConfig) {
  const m = /no-unlisted-island['"]?\s*:\s*\[[^\]]*?allow\s*:\s*\[([^\]]*)\]/s.exec(eslintConfig)
  if (!m) return null
  return [...m[1].matchAll(/['"]([^'"]+)['"]/g)].map((x) => x[1])
}

/** island → sorted `client:*` directives it is mounted with, across .astro sources. */
export function islandDirectives(islands, astroSources) {
  const found = new Map(islands.map((n) => [n, new Set()]))
  for (const src of astroSources) {
    for (const n of islands) {
      for (const tag of src.matchAll(new RegExp(`<${n}\\b([^>]*)>`, 'g'))) {
        for (const d of tag[1].matchAll(/\bclient:([a-z-]+)/g)) found.get(n).add(`client:${d[1]}`)
      }
    }
  }
  return new Map([...found].map(([n, s]) => [n, [...s].sort()]))
}

/** island → why, from a `| `Name` | `client:x` | why |` table. */
export function parseIslandRows(block) {
  const rows = new Map()
  for (const line of (block ?? '').split('\n')) {
    const cells = tableCells(line)
    if (!cells || cells.length < 3 || isRule(cells)) continue
    const m = /^`([A-Za-z]\w*)`$/.exec(cells[0])
    if (m) rows.set(m[1], cells[2])
  }
  return rows
}

export function renderIslandsTable(directives, whys) {
  const out = ['| Island | Hydration | Why |', '| --- | --- | --- |']
  for (const [n, ds] of directives) {
    const hyd = ds.length ? ds.map((d) => `\`${d}\``).join(', ') : '(not mounted)'
    out.push(`| \`${n}\` | ${hyd} | ${whys.get(n) ?? ''} |`)
  }
  return {
    body: out.join('\n'),
    unnoted: [...directives.keys()].filter((n) => !whys.get(n)),
  }
}

// ----------------------------------------------------------- fingerprint ----

/** The repo's documented shape. Every list is sorted, so the snapshot diffs cleanly. */
export function fingerprint({ files, pkg, islands, hostSources }) {
  const sorted = (xs) => [...new Set(xs)].sort(byName)
  const hosts = hostSources.flatMap((src) =>
    [...src.matchAll(/https:\/\/([a-z0-9.-]+\.[a-z]{2,})/gi)].map((m) => m[1].toLowerCase()),
  )
  return {
    files: sorted(files.filter((f) => !IGNORED.some((re) => re.test(f)))),
    scripts: sorted(Object.keys(pkg.scripts ?? {})),
    dependencies: sorted([
      ...Object.keys(pkg.dependencies ?? {}),
      ...Object.keys(pkg.devDependencies ?? {}),
    ]),
    islands: sorted([...islands].map(([n, ds]) => `${n} ${ds.join(' ')}`.trim())),
    hosts: sorted(hosts),
  }
}

/** { key: { added, removed } } for every list that differs; {} when none does. */
export function diffFingerprints(before, after) {
  const changes = {}
  for (const key of Object.keys(after)) {
    const a = new Set(before?.[key] ?? [])
    const b = new Set(after[key])
    const added = [...b].filter((x) => !a.has(x))
    const removed = [...a].filter((x) => !b.has(x))
    if (added.length || removed.length) changes[key] = { added, removed }
  }
  return changes
}

// ---------------------------------------------------------------- the repo ---

/** Everything the generator reads, from the working tree (tracked files only). */
export function readRepo(cwd = process.cwd()) {
  const read = (rel) => readFileSync(`${cwd}/${rel}`, 'utf8')
  const files = execFileSync('git', ['ls-files', '-z'], { cwd, encoding: 'utf8' })
    .split('\0')
    .filter(Boolean)
    // A file deleted in the working tree but not yet staged is gone in practice.
    .filter((f) => existsSync(`${cwd}/${f}`))
  const pkg = JSON.parse(read('package.json'))
  const allow = islandAllowlist(read('eslint.config.js')) ?? []
  const astro = files.filter((f) => f.startsWith('src/') && f.endsWith('.astro')).map(read)
  return {
    files,
    pkg,
    islands: islandDirectives(allow, astro),
    hostSources: HOST_SOURCES.filter((f) => files.includes(f)).map(read),
    docs: Object.fromEntries(DOCS.map((d) => [d, read(d)])),
    snapshot: existsSync(`${cwd}/${SNAPSHOT}`) ? JSON.parse(read(SNAPSHOT)) : null,
  }
}

/**
 * Where each generated block lives and how it is built. `render` gets the
 * block's current text (for its prose) and the repo.
 */
const BLOCKS = [
  {
    doc: 'README.md',
    name: 'scripts',
    render: (cur, repo) => renderScriptsTable(Object.keys(repo.pkg.scripts), parseScriptRows(cur)),
  },
  {
    doc: 'README.md',
    name: 'layout',
    render: (cur, repo) => renderTree(repo.files, parseTreeNotes(cur)),
  },
  {
    doc: 'README.md',
    name: 'islands',
    render: (cur, repo) => renderIslandsTable(repo.islands, parseIslandRows(cur)),
  },
  {
    doc: 'CLAUDE.md',
    name: 'commands',
    render: (cur, repo) =>
      renderCommandLines(Object.keys(repo.pkg.scripts), parseCommandLines(cur)),
  },
]

/** The docs with every block rebuilt, plus what came out without prose. */
export function regenerate(repo) {
  const docs = { ...repo.docs }
  const unnoted = []
  const problems = []
  for (const b of BLOCKS) {
    const cur = readBlock(docs[b.doc], b.name)
    if (cur === null) {
      problems.push(`${b.doc} has no docs:${b.name} block`)
      continue
    }
    const { body, unnoted: u } = b.render(cur, repo)
    docs[b.doc] = replaceBlock(docs[b.doc], b.name, body)
    unnoted.push(...u.map((key) => ({ block: `${b.doc}#${b.name}`, key })))
  }
  return { docs, unnoted, problems }
}

/** Format as the pre-commit hook would, so a fresh block compares equal. */
async function prettierFormat(text, filepath) {
  const prettier = await import('prettier')
  const options = (await prettier.resolveConfig(filepath)) ?? {}
  return prettier.format(text, { ...options, filepath })
}

/** The full report. Pure apart from the formatter. */
export async function status(repo, format = prettierFormat) {
  const { docs, unnoted, problems } = regenerate(repo)
  const formatted = {}
  for (const d of DOCS) formatted[d] = await format(docs[d], d)
  const stale = DOCS.filter((d) => formatted[d] !== repo.docs[d])
  const changes = diffFingerprints(repo.snapshot, fingerprint(repo))
  return { stale, changes, unnoted, problems, formatted }
}

// ------------------------------------------------------------------- CLI ----

function report({ stale, changes, unnoted, problems }) {
  const lines = []
  for (const p of problems) lines.push(`✗ ${p}`)
  for (const d of stale)
    lines.push(`✗ ${d}: generated blocks are out of date — run pnpm docs:write`)
  const keys = Object.keys(changes)
  if (keys.length) {
    lines.push('• The repo changed shape since the docs were last reviewed:')
    for (const k of keys) {
      for (const x of changes[k].added) lines.push(`    + ${k}: ${x}`)
      for (const x of changes[k].removed) lines.push(`    - ${k}: ${x}`)
    }
  }
  for (const u of unnoted) lines.push(`• ${u.block}: "${u.key}" has no description yet`)
  if (keys.length || unnoted.length) {
    lines.push('  Review README.md and CLAUDE.md with: pnpm docs:sync (runs /sync-docs)')
  }
  if (!lines.length) lines.push('✓ README.md and CLAUDE.md are in step with the repo.')
  console.log(lines.join('\n'))
}

async function main(argv) {
  const repo = readRepo()
  const result = await status(repo)

  if (argv.includes('--write')) {
    for (const d of result.stale) writeFileSync(d, result.formatted[d])
    if (result.stale.length)
      console.log(`Rebuilt the generated blocks in ${result.stale.join(', ')}.`)
    result.stale = []
  }
  if (argv.includes('--accept')) {
    const snap = `${JSON.stringify(fingerprint(repo), null, 2)}\n`
    writeFileSync(SNAPSHOT, await prettierFormat(snap, SNAPSHOT))
    console.log(`Recorded the repo's current shape in ${SNAPSHOT}.`)
    result.changes = {}
  }

  if (argv.includes('--json')) {
    const { formatted: _formatted, ...rest } = result
    console.log(JSON.stringify(rest, null, 2))
  } else {
    report(result)
  }
  // Only what a script can fix is an error; drift waits for a review.
  process.exitCode = result.stale.length || result.problems.length ? 1 : 0
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await main(process.argv.slice(2))
}
