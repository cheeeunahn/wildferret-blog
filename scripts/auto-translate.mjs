#!/usr/bin/env node
// The local twin of .github/workflows/translate-articles.yml, run by the
// lefthook post-commit hook: commit a Korean article and the English version
// lands as a second commit right after it, before you ever push.
//
// Same split as the workflow: scan() decides what needs translating, and
// Claude Code is only invoked when that list is non-empty. So an ordinary
// commit costs one file read, and a commit that touches no article costs
// nothing at all.
//
//   AUTO_TRANSLATE=0 git commit ...   skip it for one commit
//
// It never fails: a post-commit hook cannot undo the commit anyway, and an
// untranslated post is a valid state that the workflow picks up on push.
import { execFileSync, spawnSync } from 'node:child_process'
import { existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { scan } from './translation-status.mjs'

const EN_DIR = 'src/data/article-content/en'
const ARTICLES = 'src/data/articles.ts'

/** A Korean body or the article index — not an English file, which is our own output. */
export function touchesKoreanArticles(files) {
  return files.some((f) => f === ARTICLES || /^src\/data\/article-content\/[^/]+\.ts$/.test(f))
}

/** Pending posts need writing, problems need repairing; /translate-articles does both. */
export function slugsToTranslate({ pending, problems }) {
  return [...new Set([...pending, ...problems].map((e) => e.slug))]
}

const git = (...args) => execFileSync('git', args, { encoding: 'utf8' }).trim()
const log = (msg) => console.log(`[auto-translate] ${msg}`)

function main() {
  // Set on the translation commit itself, so its own post-commit is a no-op.
  if (process.env.AUTO_TRANSLATE === '0') return

  // Rebases, merges, and cherry-picks replay commits and fire post-commit for
  // each one; translating in the middle of that would interleave new commits.
  const inProgress = ['rebase-merge', 'rebase-apply', 'MERGE_HEAD', 'CHERRY_PICK_HEAD']
  if (inProgress.some((p) => existsSync(git('rev-parse', '--git-path', p)))) return

  const changed = git('diff-tree', '--root', '--no-commit-id', '--name-only', '-r', 'HEAD')
  if (!touchesKoreanArticles(changed.split('\n'))) return

  const slugs = slugsToTranslate(scan())
  if (slugs.length === 0) return

  // The commit below stages these paths wholesale; never sweep up edits of yours.
  if (git('status', '--porcelain', '--', EN_DIR, ARTICLES)) {
    log(`${ARTICLES} or ${EN_DIR}/ has uncommitted changes — skipping.`)
    log(`Commit or stash them, then run: claude "/translate-articles ${slugs.join(' ')}"`)
    return
  }

  log(`Translating ${slugs.join(', ')} with Claude Code (skip with AUTO_TRANSLATE=0)…`)
  const claude = spawnSync(
    'claude',
    [
      '-p',
      `Run \`/translate-articles ${slugs.join(' ')}\`. Follow that command exactly. ` +
        'Write and verify the files, but do not commit: the hook that invoked you does that. ' +
        'End with one bullet per slug and a "Needs a human" list.',
      '--allowed-tools',
      'Read,Write,Edit,Grep,Glob,Bash(pnpm:*),Bash(node scripts/translation-status.mjs:*),Bash(git status:*),Bash(git diff:*)',
      '--max-turns',
      '120',
    ],
    { stdio: ['ignore', 'inherit', 'inherit'] },
  )
  if (claude.error) {
    log(`Could not run claude (${claude.error.code}) — the push workflow will translate instead.`)
    return
  }

  git('add', '--', EN_DIR, ARTICLES)
  if (spawnSync('git', ['diff', '--cached', '--quiet']).status === 0) {
    log('Claude produced no changes — nothing to commit.')
    return
  }
  // Runs the pre-commit hook (eslint, prettier) like any other commit.
  execFileSync(
    'git',
    [
      'commit',
      '-m',
      `content: add English versions of ${slugs.join(' ')}`,
      '-m',
      'Generated by scripts/auto-translate.mjs.',
      '-m',
      'Co-Authored-By: Claude <noreply@anthropic.com>',
    ],
    { stdio: 'inherit', env: { ...process.env, AUTO_TRANSLATE: '0' } },
  )
  log('Committed. Review it before you push.')
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  try {
    main()
  } catch (err) {
    log(`Failed: ${err.message}`)
  }
}
