#!/usr/bin/env node
// The local twin of .github/workflows/sync-docs.yml, run by the lefthook
// post-commit hook: commit a change to the repo's structure (a new file, a
// renamed script, a new island) and the README/CLAUDE.md update lands as a
// second commit right after it, before you push.
//
// Same split as auto-translate.mjs: docs-sync.mjs decides, and Claude Code runs
// only when there is prose to review. A commit that only leaves generated
// blocks stale is fixed by `--write` alone, with no model; a commit that
// changes nothing documented costs one scan.
//
//   AUTO_SYNC_DOCS=0 git commit ...   skip it for one commit
//
// It never fails: a post-commit hook cannot undo the commit anyway, and
// unreviewed docs are a valid state that the workflow picks up on push.
import { execFileSync, spawnSync } from 'node:child_process'
import { existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { DOCS, SNAPSHOT, readRepo, status } from './docs-sync.mjs'

/** The only paths this hook ever stages. */
export const OWNED = [...DOCS, SNAPSHOT]

/** What the scan asks for: nothing, a mechanical rebuild, or a prose review. */
export function plan({ stale, changes, unnoted, problems }) {
  if (problems.length || Object.keys(changes).length || unnoted.length) return 'review'
  if (stale.length) return 'rebuild'
  return 'none'
}

const git = (...args) => execFileSync('git', args, { encoding: 'utf8' }).trim()
const log = (msg) => console.log(`[auto-sync-docs] ${msg}`)
const run = (args) => execFileSync('node', ['scripts/docs-sync.mjs', ...args], { stdio: 'inherit' })

function commit(subject, body) {
  git('add', '--', ...OWNED)
  if (spawnSync('git', ['diff', '--cached', '--quiet']).status === 0) {
    log('Nothing changed — nothing to commit.')
    return
  }
  // Runs the pre-commit hook (prettier) like any other commit.
  execFileSync(
    'git',
    ['commit', '-m', subject, '-m', body, '-m', 'Co-Authored-By: Claude <noreply@anthropic.com>'],
    {
      stdio: 'inherit',
      env: { ...process.env, AUTO_SYNC_DOCS: '0', AUTO_TRANSLATE: '0', AUTO_CARD_IMAGE: '0' },
    },
  )
  log('Committed. Review it before you push.')
}

async function main() {
  // Set on this hook's own commit, so its post-commit is a no-op.
  if (process.env.AUTO_SYNC_DOCS === '0') return

  // Rebases, merges and cherry-picks replay commits and fire post-commit for
  // each one; committing in the middle of that would interleave new commits.
  const inProgress = ['rebase-merge', 'rebase-apply', 'MERGE_HEAD', 'CHERRY_PICK_HEAD']
  if (inProgress.some((p) => existsSync(git('rev-parse', '--git-path', p)))) return

  const todo = plan(await status(readRepo()))
  if (todo === 'none') return

  // The commit below stages these paths wholesale; never sweep up edits of yours.
  if (git('status', '--porcelain', '--', ...OWNED)) {
    log(`${OWNED.join(', ')} have uncommitted changes — skipping.`)
    log('Commit or stash them, then run: pnpm docs:sync')
    return
  }

  if (todo === 'rebuild') {
    run(['--write'])
    commit('docs: rebuild the generated blocks', 'Generated by scripts/auto-sync-docs.mjs.')
    return
  }

  log('The repo changed shape; reviewing the docs with Claude Code (skip with AUTO_SYNC_DOCS=0)…')
  const claude = spawnSync(
    'claude',
    [
      '-p',
      'Run `/sync-docs`. Follow that command exactly. Edit and verify README.md and ' +
        'CLAUDE.md, but do not commit: the hook that invoked you does that. ' +
        'End with one bullet per edit and a "Needs a human" list.',
      '--allowed-tools',
      'Read,Edit,Grep,Glob,Bash(node scripts/docs-sync.mjs:*),Bash(pnpm exec prettier:*),Bash(git status:*),Bash(git diff:*),Bash(git log:*)',
      '--max-turns',
      '80',
    ],
    { stdio: ['ignore', 'inherit', 'inherit'] },
  )
  if (claude.error) {
    log(
      `Could not run claude (${claude.error.code}) — the push workflow will sync the docs instead.`,
    )
    return
  }
  commit(
    'docs: sync README.md and CLAUDE.md with the repo',
    'Generated by scripts/auto-sync-docs.mjs.',
  )
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  try {
    await main()
  } catch (err) {
    log(`Failed: ${err.message}`)
  }
}
